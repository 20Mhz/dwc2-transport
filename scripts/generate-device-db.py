#!/usr/bin/env python3
"""Generate the diagnostic app's C table; the SDK ABI is independent of it."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    database = json.loads((ROOT / 'data/device-identification-v1.json').read_text())
    assert database['schema'] == 1
    seen = set()
    lines = ['/* Generated by scripts/generate-device-db.py; do not edit. SPDX-License-Identifier: MIT */',
             '#ifndef DIAG_DEVICE_DB_H', '#define DIAG_DEVICE_DB_H',
             '#include <stdint.h>', '#include <stddef.h>',
             'struct diag_identity { uint16_t vendor, product; const char *label, *mode, *confidence, *model, *caveat, *category, *state_category, *sources; };',
             '#define DIAG_DB_VERSION ' + json.dumps(database['version']),
             'static const struct diag_identity diag_identities[] = {']
    for item in database['devices']:
        identity = item['vendor_id'], item['product_id']
        assert all(isinstance(x, int) and 0 <= x <= 65535 for x in identity) and identity not in seen
        seen.add(identity)
        refs = json.dumps([database['sources'][key]['url'] for key in item['sources']], separators=(',', ':'))
        strings = [item[key] for key in ('label', 'mode', 'confidence', 'model', 'caveat', 'identity_category', 'state_category')] + [refs]
        lines.append('    {' + ', '.join([str(x) for x in identity] + [json.dumps(x) for x in strings]) + '},')
    lines += ['};', 'static inline const struct diag_identity *diag_identify(uint16_t vendor, uint16_t product) {',
              '    for (size_t i = 0; i < sizeof(diag_identities)/sizeof(diag_identities[0]); i++)',
              '        if (diag_identities[i].vendor == vendor && diag_identities[i].product == product) return &diag_identities[i];',
              '    return NULL;', '}', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'tools/diagnostics/device_db.h'
    data = generate()
    if args.check:
        if path.read_text() != data:
            raise SystemExit('generated device table is stale; run scripts/generate-device-db.py')
    else:
        path.write_text(data)


if __name__ == '__main__':
    main()
